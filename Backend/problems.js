// Only the PUBLIC fields of a problem ever leave the server.
export function publicProblem(p) {
  const { id, title, difficulty, statement, samples } = p;
  return { id, title, difficulty, statement, samples };
}

// Compact list used for the interviewer-facing problem bank picker.
export function listProblems() {
  return PROBLEMS.map((p) => ({ id: p.id, title: p.title, difficulty: p.difficulty }));
}
